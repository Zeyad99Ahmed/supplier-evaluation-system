// Minimal .env reader/writer (no secrets are ever printed).
const fs = require('fs');
const crypto = require('crypto');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const LOCAL_ENV = path.join(ROOT, '.env.local');

function parseEnv(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !line.trim().startsWith('#')) out[m[1]] = m[2].replace(/^"(.*)"$/, '$1');
  }
  return out;
}

const rand = (bytes = 32) => crypto.randomBytes(bytes).toString('base64url');

// Creates .env.local with freshly generated random secrets the first time (git-ignored).
function ensureLocalEnv() {
  if (fs.existsSync(LOCAL_ENV)) return parseEnv(LOCAL_ENV);
  const values = {
    PG_PORT: '5433',
    PG_SUPERUSER_PASSWORD: rand(18),
    AUTH_DB_PASSWORD: rand(18),
    SUPPLIER_DB_PASSWORD: rand(18),
    ORDER_DB_PASSWORD: rand(18),
    EVALUATION_DB_PASSWORD: rand(18),
    JWT_SECRET: rand(48),
    INTERNAL_JWT_SECRET: rand(48),
    ADMIN_EMAIL: 'admin@ses.local',
    ADMIN_PASSWORD: 'Admin' + crypto.randomInt(100000, 999999) + 'x',
    ADMIN_NAME: 'Procurement Admin',
    EXCHANGE_API_KEY: '',
    APPROVAL_THRESHOLD_EGP: '50000',
  };
  const text = '# Local development secrets - generated by scripts/local-up.js. NEVER COMMIT (listed in .gitignore).\n' +
    Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n') + '\n';
  fs.writeFileSync(LOCAL_ENV, text, { mode: 0o600 });
  console.log('Created .env.local with new random secrets (git-ignored).');
  return values;
}

module.exports = { parseEnv, ensureLocalEnv, LOCAL_ENV, ROOT, rand };
