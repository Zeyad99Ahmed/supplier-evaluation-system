// Builds frontend/*.html from frontend/pages/*.body.html + one shared page shell, so every page has the
// same Content-Security-Policy, navigation and scripts. Run: node scripts/build-pages.js
const fs = require('fs');
const path = require('path');

const FRONT = path.join(__dirname, '..', 'frontend');
const PAGES = [
  ['dashboard', 'Dashboard'], ['suppliers', 'Suppliers'], ['supplier', 'Supplier'],
  ['orders', 'Orders'], ['evaluations', 'Evaluations'], ['admin', 'Admin'],
];
const CSP = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self' http://localhost:4001 http://localhost:4002 http://localhost:4003 http://localhost:4004 http://*.localhost.floci.io:4566 http://*.execute-api.localhost:4566 https://*.amazonaws.com; object-src 'none'; base-uri 'self'; form-action 'self'";

for (const [name, title] of PAGES) {
  const body = fs.readFileSync(path.join(FRONT, 'pages', `${name}.body.html`), 'utf8');
  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="${CSP}">
  <title>${title} · Supplier Directory</title>
  <link rel="stylesheet" href="css/style.css">
</head>
<body>
  <!-- generated by scripts/build-pages.js from pages/${name}.body.html -->
  <div id="nav"></div>
  <main>
${body.trimEnd()}
  </main>
  <div id="toast" role="status" aria-live="polite"></div>
  <script src="js/config.js"></script>
  <script src="js/api.js"></script>
  <script src="js/ui.js"></script>
  <script src="js/auth.js"></script>
  <script src="js/${name}.js"></script>
</body>
</html>
`;
  fs.writeFileSync(path.join(FRONT, `${name}.html`), html);
  console.log(`built frontend/${name}.html`);
}
