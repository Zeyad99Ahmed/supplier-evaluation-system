#!/usr/bin/env bash
# Publishes the website to S3 (Lab 7 Part 4) and writes js/config.js with the four API Gateway URLs.
# Only frontend files go into the bucket - never backend code, .env files or zips.
source "$(dirname "$0")/lib.sh"
[ -f "$ROOT/infra/floci-urls.env" ] || { echo "Run bash infra/deploy.sh all first (no infra/floci-urls.env)"; exit 1; }
# shellcheck disable=SC1091
source "$ROOT/infra/floci-urls.env"

BUILD="dist/web"
rm -rf "$BUILD"; mkdir -p "$BUILD"
node "$ROOT/scripts/build-pages.js" >/dev/null
cp -r "$ROOT/frontend/"*.html "$ROOT/frontend/css" "$ROOT/frontend/js" "$BUILD/"
cat > "$BUILD/js/config.js" <<EOF
// Generated by infra/deploy-frontend.sh for $TARGET - public API addresses only, no secrets.
window.SES_CONFIG = {
  AUTH_API: '$AUTH_API',
  SUPPLIER_API: '$SUPPLIER_API',
  ORDER_API: '$ORDER_API',
  EVALUATION_API: '$EVALUATION_API',
  ENVIRONMENT: '$TARGET',
};
EOF

aws s3 mb "s3://$WEB_BUCKET" 2>/dev/null || true
aws s3 website "s3://$WEB_BUCKET" --index-document index.html --error-document index.html || true
if [ "$TARGET" = "aws" ]; then
  # Real AWS blocks public buckets by default; allow public READ of this one bucket only (Lab 7 Part 6).
  aws s3api put-public-access-block --bucket "$WEB_BUCKET" --public-access-block-configuration BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=false,RestrictPublicBuckets=false
  sed "s/cloud-issue-web/$WEB_BUCKET/" "$ROOT/infra/iam/s3-public-read-policy.json" > "$ROOT/dist/s3-policy.json"
  aws s3api put-bucket-policy --bucket "$WEB_BUCKET" --policy "file://dist/s3-policy.json"
fi
aws s3 sync "$BUILD" "s3://$WEB_BUCKET" --delete --exclude "*" --include "*.html" --content-type "text/html; charset=utf-8"
aws s3 cp "$BUILD/css" "s3://$WEB_BUCKET/css" --recursive --content-type text/css
aws s3 cp "$BUILD/js" "s3://$WEB_BUCKET/js" --recursive --content-type text/javascript
aws s3 ls "s3://$WEB_BUCKET" --recursive
echo "Website: $SITE_URL"
